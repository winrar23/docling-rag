import { plural } from "@/lib/plural";

test.each([
  [1, "фрагмент"],
  [2, "фрагмента"],
  [5, "фрагментов"],
  [11, "фрагментов"],
  [12, "фрагментов"],
  [14, "фрагментов"],
  [21, "фрагмент"],
  [111, "фрагментов"],
])("plural(%i) → «%s»", (n, expected) => {
  expect(plural(n, "фрагмент", "фрагмента", "фрагментов")).toBe(expected);
});
